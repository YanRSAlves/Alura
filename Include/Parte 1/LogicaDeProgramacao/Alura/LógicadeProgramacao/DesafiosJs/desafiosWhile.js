/*
Crie um contador que comece em 1 e vá até 10 
usando um loop while. Mostre cada número.

*/
console.log('Desafio 1');
let inicio = 1, final = 10;
while(inicio <= final){
    console.log(inicio)
    inicio++;
}
/*
Crie um contador que começa em 10 e vá até 0 
usando um loop while. Mostre cada número.
*/
console.log('Desafio 2');
